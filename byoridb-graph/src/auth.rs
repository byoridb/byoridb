pub struct Session {
    pub id: i64,
    pub username: String,
    pub roles: Vec<String>,
    pub created_at: SystemTime,
    pub expires_at: SystemTime,
}

impl Session {
    /// Returns true if the session has passed its expiration time.
    pub fn is_expired(&self) -> bool {
        SystemTime::now() >= self.expires_at
    }
}

